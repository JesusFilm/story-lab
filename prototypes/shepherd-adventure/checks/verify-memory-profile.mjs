import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const source=readFileSync(new URL('../src/memory-profile.js',import.meta.url),'utf8');
let timers=0;
const make=search=>({URLSearchParams,URL,location:{search,href:'http://localhost/'},window:{},navigator:{},innerWidth:1280,innerHeight:720,devicePixelRatio:1,crossOriginIsolated:false,matchMedia:()=>({matches:false}),performance:{now:()=>1},document:{hidden:false,hasFocus:()=>true,getElementById:()=>null,images:[]},addEventListener(){},setInterval(){timers++;return 1;},clearInterval(){}});
const disabled=make('');vm.runInNewContext(source,disabled);assert.equal(disabled.window.shepherdMemory,undefined);assert.equal(timers,0);
const enabled=make('?profile');vm.runInNewContext(source,enabled);
const bytes=new ArrayBuffer(120),image={width:1024,height:512};
const texture={isTexture:true,source:{data:image},generateMipmaps:true};
const material={map:texture,normalMap:texture};
const geometry={attributes:{position:{array:new Float32Array(bytes)},normal:{array:new Float32Array(bytes)}},morphAttributes:{},index:null};
const mesh={isMesh:true,geometry,material};
const root={traverse:fn=>[mesh,mesh].forEach(fn)};
let result=enabled.window.shepherdMemory.inventory(root);
assert.equal(result.geometryArrayBufferBytes,120,'Shared typed-array backing stores count once');
assert.equal(result.textureObjects,1,'Material slots and mesh instances share the texture');
assert.equal(result.decodedImageRGBAEstimatedBytes,1024*512*4);
assert.equal(result.textureRGBAEstimatedBytes,Math.round(1024*512*4*4/3));
material.normalMap={...texture};result=enabled.window.shepherdMemory.inventory(root);
assert.equal(result.textureObjects,2);assert.equal(result.imageSources,1,'Two textures can reference a single decoded image');
assert.equal(result.textureRGBAEstimatedBytes,Math.round(1024*512*4*4/3*2));
assert.equal(enabled.window.shepherdMemory.report().samples[0].heap,null,'Unsupported heap counter is unavailable, never zero');
console.log('Memory profile: opt-in, shared-resource accounting, mipmaps and unsupported counters passed.');
